// Render declarative m3.toml values into files for the target Mac:
//   [[projects.<name>.agents]] → launchd plist, [brew] → Brewfile, [[tools]] → install script
import type { Agent, Dict, Project } from "../types.js";
import { fail, shq } from "../util.js";

const xml = (s: unknown) => String(s).replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;");
/** ~/ at the start or after ':' → __HOME__/ (substituted on deploy) */
const home = (s: unknown) => String(s).replace(/(^|:)~\//g, "$1__HOME__/");

const str = (k: string, v: unknown) => `  <key>${k}</key><string>${xml(home(v))}</string>\n`;
const bool = (k: string, v: boolean) => `  <key>${k}</key><${v ? "true" : "false"}/>\n`;
const int = (k: string, v: number) => `  <key>${k}</key><integer>${Math.trunc(v)}</integer>\n`;
const dict = (o: Dict, ints = false) => "<dict>" + Object.entries(o).map(([k, v]) =>
  `<key>${xml(k)}</key>` + (ints ? `<integer>${Math.trunc(Number(v))}</integer>` : `<string>${xml(home(v))}</string>`)).join("") + "</dict>";

const AGENT_KEYS = new Set(["label", "program", "working_dir", "env", "run_at_load", "keep_alive", "throttle", "interval", "calendar", "log", "stdout", "stderr"]);

/** one [[projects.<name>.agents]] entry → launchd plist */
export function renderAgent(p: Project, a: Dict): Agent {
  const where = `projects.${p.name}.agents`;
  if (typeof a.label !== "string") fail(`${where}: label is required`);
  if (!Array.isArray(a.program) || !a.program.length) fail(`${where} (${a.label}): program = ["/path/to/bin", "arg", ...] is required`);
  const unknown = Object.keys(a).filter((k) => !AGENT_KEYS.has(k));
  if (unknown.length) fail(`${where} (${a.label}): unknown keys ${unknown.join(", ")}`);
  let body = str("Label", a.label);
  body += "  <key>ProgramArguments</key>\n  <array>\n" + a.program.map((x: unknown) => `    <string>${xml(home(x))}</string>\n`).join("") + "  </array>\n";
  if (a.working_dir) body += str("WorkingDirectory", a.working_dir);
  if (a.env) body += `  <key>EnvironmentVariables</key>\n  ${dict(a.env)}\n`;
  if (a.run_at_load != null) body += bool("RunAtLoad", !!a.run_at_load);
  if (a.keep_alive != null) body += bool("KeepAlive", !!a.keep_alive);
  if (a.throttle != null) body += int("ThrottleInterval", a.throttle);
  if (a.interval != null) body += int("StartInterval", a.interval);
  if (a.calendar) body += `  <key>StartCalendarInterval</key>\n  ${dict(a.calendar, true)}\n`;
  const out = a.stdout ?? a.log, err = a.stderr ?? a.log;
  if (out) body += str("StandardOutPath", out);
  if (err) body += str("StandardErrorPath", err);
  return {
    label: a.label,
    plist: '<?xml version="1.0" encoding="UTF-8"?>\n<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">\n' +
      `<plist version="1.0">\n<dict>\n${body}</dict>\n</plist>\n`,
  };
}

/** [brew] { taps, formulae, casks, mas } → Brewfile. formula: "name" or { name, link } */
export function renderBrewfile(b: Dict): string {
  const q = (s: unknown) => JSON.stringify(String(s));
  const lines = ["# generated by m3 from [brew] in m3.toml"];
  for (const t of b.taps ?? []) lines.push(`tap ${q(t)}`);
  for (const f of b.formulae ?? []) {
    if (typeof f === "string") lines.push(`brew ${q(f)}`);
    else lines.push(`brew ${q(f.name)}` + (f.link != null ? `, link: ${!!f.link}` : ""));
  }
  for (const c of b.casks ?? []) lines.push(`cask ${q(c)}`);
  for (const [name, id] of Object.entries(b.mas ?? {})) lines.push(`mas ${q(name)}, id: ${Number(id)}`);
  return lines.join("\n") + "\n";
}

/** [[tools]] { name, bin | check, install | manual } → idempotent zsh script */
export function renderTools(tools: Dict[]): string {
  const sh = (s: string) => String(s).replace(/(^|[\s:=])~\//g, "$1$HOME/");
  let out = "#!/bin/zsh\n# generated by m3 from [[tools]] in m3.toml\nset -u\nexport PATH=/opt/homebrew/bin:$HOME/.local/bin:$PATH\nmkdir -p ~/.local/bin\n";
  for (const t of tools) {
    if (typeof t.name !== "string") fail("[[tools]]: name is required");
    if (!t.install && !t.manual) fail(`[[tools]] ${t.name}: install or manual is required`);
    const bin = t.bin ? sh(t.bin) : "";
    const test = t.check ? sh(t.check) : bin ? `command -v ${shq(bin.split("/").pop()!)} >/dev/null 2>&1 || [ -x "${bin}" ]` : "";
    const act = t.install
      ? `echo "  - ${t.name}: installing"; { ${sh(t.install)} ; } || echo "  x ${t.name}: install failed"`
      : `echo "  ! ${t.name}: manual: "${shq(String(t.manual))}`;
    out += `\n# ${t.name}\n` + (test ? `if ${test}; then echo "  o ${t.name}"; else ${act}; fi\n` : `${act}\n`);
  }
  return out + "exit 0\n";
}
